import "server-only";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import type { Database } from "./database.types";

const globalForDb = globalThis as unknown as { supabase?: SupabaseClient<Database> };

/**
 * Server-side Supabase client. It uses the secret key, which bypasses row
 * level security, so every query must filter by the signed-in user itself.
 * Created on first use so builds without the env vars still work.
 */
export function db() {
  if (!globalForDb.supabase) {
    const url = process.env.SUPABASE_URL;
    const key = process.env.SUPABASE_SECRET_KEY;
    if (!url || !key) {
      throw new Error("SUPABASE_URL and SUPABASE_SECRET_KEY must be set");
    }
    globalForDb.supabase = createClient<Database>(url, key, {
      auth: { persistSession: false, autoRefreshToken: false },
    });
  }
  return globalForDb.supabase;
}

type Result = { data: unknown; error: { message: string } | null };

/** Awaits a query and returns its data, throwing if Supabase reports an error. */
export async function run<R extends Result>(query: PromiseLike<R>): Promise<Extract<R, { error: null }>["data"]> {
  const { data, error } = await query;
  if (error) {
    throw new Error(error.message);
  }
  return data as Extract<R, { error: null }>["data"];
}

/** Ids are generated by the database. Use this before putting one into a PostgREST `or` filter. */
export const isId = (value: string) => /^[\w-]+$/.test(value);

/** Postgres error code for a unique constraint violation. */
export const UNIQUE_VIOLATION = "23505";
